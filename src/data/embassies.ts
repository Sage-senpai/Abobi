export function findEmbassies(filter: {
  representingCountry?: string;
  hostCountry?: string;
  query?: string;
}): Embassy[] {
  const q = filter.query?.toLowerCase().trim();
  return EMBASSIES.filter((e) => {
    if (filter.representingCountry && e.representingCountry !== filter.representingCountry) return false;
    if (filter.hostCountry && e.hostCountry !== filter.hostCountry) return false;
    if (q) {
      const hay = `${e.representingCountry} ${e.hostCountry} ${e.hostCity} ${e.servicesOffered.join(" ")}`.toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });
}

export function listRepresentingCountries(): string[] {
  return Array.from(new Set(EMBASSIES.map((e) => e.representingCountry))).sort();
}

export function listHostCountries(): string[] {
  return Array.from(new Set(EMBASSIES.map((e) => e.hostCountry))).sort();
}
